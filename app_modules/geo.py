# 120km 以外还不确定属于哪个城市：这是"就近猜"的诚实上限，
# 不是精度参数——调大只会把"在野外"说成"在某市"。
MAX_KM = 120.0


def distance_km(lat_a, lng_a, lat_b, lng_b):
    """两点大圆距离（公里）。"""
    r = 6371.0088
    p1, p2 = math.radians(lat_a), math.radians(lat_b)
    dp = p2 - p1
    dl = math.radians(lng_b - lng_a)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(min(1.0, math.sqrt(h)))


def city_of(lat, lng):
    """返回 {"city","km","cuisines"}；坐标非法或离所有锚点都远，返回 None。

    调用方拿到 None 必须走"手填城市"，不要拿 None 拼一个看起来像城市名的字符串。
    """
    try:
        lat = float(lat)
        lng = float(lng)
    except (TypeError, ValueError):
        return None
    if not (-90.0 <= lat <= 90.0 and -180.0 <= lng <= 180.0):
        return None
    best, best_km = None, None
    for name, clat, clng, cuisines in CITIES:
        km = distance_km(lat, lng, clat, clng)
        if best_km is None or km < best_km:
            best, best_km = (name, cuisines), km
    if best is None or best_km > MAX_KM:
        return None
    return {"city": best[0], "km": round(best_km, 1), "cuisines": list(best[1])}


def cuisines_of(city):
    """手填的城市名也能查到菜系标签；查不到给空表，不硬套一个。"""
    if not city:
        return []
    target = str(city).strip()
    for name, _lat, _lng, cuisines in CITIES:
        if name == target:
            return list(cuisines)
    return []


def known_cities():
    return [name for name, _lat, _lng, _c in CITIES]
