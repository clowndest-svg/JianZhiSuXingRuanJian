import assert from 'node:assert/strict';
import vm from 'node:vm';
import {makeCtx,loadJs} from './dom-fixture.mjs';
const h=makeCtx();loadJs(h.context);
const opened=[],native=[],legacy=[];
h.sandbox.window.__currentExercises=[{name:'1. 桌下反向划船（居家）'}];
h.sandbox.window.open=(...args)=>opened.push(args);
h.sandbox.window.AndroidBridge=undefined;
vm.runInContext('openExerciseVideo(0)',h.context);
assert.equal(opened.length,1);
const url=new URL(opened[0][0]);assert.equal(url.origin,'https://www.douyin.com');
assert.equal(decodeURIComponent(url.pathname),'/search/桌下反向划船（居家） 标准动作 教学');
assert.equal(url.searchParams.get('type'),'video');assert.equal(opened[0][2],'noopener,noreferrer');
h.sandbox.window.AndroidBridge={searchDouyin:k=>native.push(k),openBrowser:u=>legacy.push(u)};
vm.runInContext('openExerciseVideo(0)',h.context);
assert.deepEqual(native,['桌下反向划船（居家） 标准动作 教学']);assert.equal(legacy.length,0);
h.sandbox.window.AndroidBridge={openBrowser:u=>legacy.push(u)};
vm.runInContext('openExerciseVideo(0)',h.context);assert.equal(legacy[0],opened[0][0]);
vm.runInContext('openExerciseVideo(99)',h.context);assert.equal(legacy.length,1);
console.log('PASS: desktop Douyin video search, native search bridge, old APK web fallback, invalid exercise');
